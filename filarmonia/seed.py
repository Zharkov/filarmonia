    with app.app_context():
        if reset:
            db.drop_all()
        db.create_all()

        if User.query.count() == 0:
            admin = User(login=ADMIN_LOGIN, name="Администратор сайта", role="admin")
            admin.set_password(ADMIN_PASSWORD)
            db.session.add(admin)

        for key, value, title, group, kind in SETTINGS:
            if db.session.get(Setting, key) is None:
                db.session.add(Setting(key=key, value=value, title=title, group=group, kind=kind))
        db.session.commit()

        # Страницы
        by_title = {}
        for title, parent, template, sort, content in PAGES:
            pg = Page.query.filter_by(title=title).first()
            if pg is None:
                pg = Page(title=title, slug=slugify(title), template=template, sort=sort, content=content)
                db.session.add(pg)
            by_title[title] = pg
        db.session.commit()
        for title, parent, *_ in PAGES:
            if parent:
                by_title[title].parent_id = by_title[parent].id
        db.session.commit()

        # Меню
        if MenuItem.query.count() == 0:
            for title, url, page_title, sort, children in MENU:
                parent = MenuItem(
                    title=title, url=url or "",
                    page_id=by_title[page_title].id if page_title else None, sort=sort,
                )
                db.session.add(parent)
                db.session.commit()
                for i, child_title in enumerate(children):
                    db.session.add(MenuItem(
                        title=child_title, page_id=by_title[child_title].id,
                        parent_id=parent.id, sort=(i + 1) * 10,
                    ))
            db.session.commit()

        # Площадки и жанры
        if Venue.query.count() == 0:
            for name, address in VENUES:
                db.session.add(Venue(name=name, slug=slugify(name), address=address))
        if Category.query.count() == 0:
            for i, name in enumerate(CATEGORIES):
                db.session.add(Category(name=name, slug=slugify(name), sort=(i + 1) * 10))
        db.session.commit()

        # Настройки
        demo.photo("hero-hall.jpg", "Концертный зал филармонии", 3, (1920, 1080))
        Setting.set("hero_video", demo.hero_video("hero-hall.jpg", "hero.mp4") or "")
        Setting.set("hero_poster", "hero-hall.jpg")
        db.session.commit()

        # Коллективы
        if Collective.query.count() == 0:
            for i, (name, lead, ann, desc, contacts) in enumerate(COLLECTIVES):
                c = Collective(
                    name=name, slug=slugify(name), lead=lead, annotation=ann,
                    description=desc, contacts=contacts, sort=(i + 1) * 10,
                )
                db.session.add(c)
                db.session.commit()
                for j in range(3):
                    file = demo.photo(f"col-{i}-{j}.jpg", name.split(",")[0], i * 3 + j + 5, (1200, 800))
                    db.session.add(MediaItem(kind="photo", file=file, collective_id=c.id, sort=j * 10))
                video = demo.clip("demo-clip.mp4")
                if video:
                    db.session.add(MediaItem(
                        kind="video", file=video, title="Фрагмент концерта",
                        preview=demo.photo(f"col-{i}-v.jpg", "Видео: " + name.split(",")[0], i + 21, (1200, 800)),
                        collective_id=c.id, sort=100,
                    ))
            db.session.commit()

        # Афиша
        collectives = Collective.query.all()
        venues = Venue.query.all()
        if Event.query.count() == 0:
            for i, spec in enumerate(EVENTS):
                starts = (datetime.now() + timedelta(days=spec["days"])).replace(
                    hour=spec["hour"], minute=spec["minute"], second=0, microsecond=0
                )
                category = Category.query.filter_by(name=spec["cat"]).first()
                poster_file = demo.poster(
                    f"poster-{i}.jpg", spec["title"], spec["ann"],
                    f"{starts.day:02d}.{starts.month:02d}.{starts.year} · {spec['hour']}:{spec['minute']:02d}", i,
                )
                ev = Event(
                    title=spec["title"], slug=slugify(spec["title"]), poster=poster_file,
                    starts_at=starts, duration_min=spec["dur"], age_limit=spec["age"],
                    price_min=spec["price"][0], price_max=spec["price"][1],
                    venue_id=venues[i % 2].id, category_id=category.id if category else None,
                    annotation=spec["ann"], description=spec["desc"], performers=spec["perf"],
                    organizer="ОГБУК «Смоленская областная филармония»",
                    ticket_url="https://smolensk-filarmonia.ru/tickets",
                    tickets_left="осталось более 50 билетов",
                    show_pushkin=spec["pushkin"],
                    # текст пуст — на странице подставится общий из «Настроек»
                    pushkin_text="",
                    show_benefits=spec["benefits"],
                    benefits_text=BENEFITS_TEXT if spec["benefits"] else "",
                    is_new=spec.get("new", False),
                    is_published=True,
                )
                db.session.add(ev)
                db.session.commit()

                if spec["pushkin"]:
                    db.session.add(EventBadge(
                        event_id=ev.id, text="Пушкинская карта", style="brick", position="top-left",
                        hint="Билет можно оплатить Пушкинской картой через приложение «Госуслуги Культура».",
                        sort=10,
                    ))
                if spec["benefits"]:
                    db.session.add(EventBadge(
                        event_id=ev.id, text="Есть льготы", style="gold", position="bottom-left",
                        hint="Пенсионерам — 250 ₽, дети до 7 лет — бесплатно в сопровождении взрослых.",
                        sort=20,
                    ))
                if spec.get("new"):
                    db.session.add(EventBadge(
                        event_id=ev.id, text="Премьера сезона", style="ink", position="top-right",
                        hint="Программа впервые прозвучит в этом сезоне.", sort=30,
                    ))

                if i < 4:
                    ev.collectives = [collectives[i % len(collectives)]]
                    for j in range(3):
                        file = demo.photo(f"ev-{i}-{j}.jpg", "С прошлого концерта", i * 5 + j + 31, (1400, 900))
                        db.session.add(MediaItem(kind="photo", file=file, event_id=ev.id, sort=j * 10))
                    video = demo.clip("demo-clip.mp4")
                    if video:
                        db.session.add(MediaItem(
                            kind="video", file=video,
                            title="Видеоприглашение от артистов",
                            preview=demo.photo(f"ev-{i}-v.jpg", "Видео артистов", i + 41, (1400, 900)),
                            event_id=ev.id, sort=100,
                        ))
                db.session.commit()

        # Новости
        if News.query.count() == 0:
            for i, (title, lead, content) in enumerate(NEWS):
                db.session.add(News(
                    title=title, slug=slugify(title), lead=lead, content=content,
                    image=demo.photo(f"news-{i}.jpg", title, i + 51, (1400, 900)),
                    published_at=datetime.now() - timedelta(days=i * 3 + 1),
                ))
            db.session.commit()

        # Галерея
        if Album.query.count() == 0:
            for i, title in enumerate(["Концерты сезона 2026", "Фестиваль имени М. И. Глинки",
                                       "Гастроли по области"]):
                album = Album(title=title, slug=slugify(title), year=2026 - i,
                              cover=demo.photo(f"alb-{i}.jpg", title, i + 61, (1400, 900)))
                db.session.add(album)
                db.session.commit()
                for j in range(6):
                    db.session.add(MediaItem(
                        kind="photo", file=demo.photo(f"alb-{i}-{j}.jpg", title, i * 6 + j + 71, (1400, 900)),
                        album_id=album.id, sort=j * 10,
                    ))
            db.session.commit()

        # Документы
        if Document.query.count() == 0:
            for i, (title, category, year) in enumerate(DOCUMENTS):
                db.session.add(Document(title=title, category=category, year=year,
                                        url="#", sort=(i + 1) * 10))
            db.session.commit()

        # Баннеры
        if Banner.query.count() == 0:
            for i, (title, url) in enumerate(BANNERS):
                db.session.add(Banner(title=title, url=url, place="partners", sort=(i + 1) * 10))
            db.session.commit()

        # Обращения граждан (демо)
        if Appeal.query.count() == 0:
            for name, email, phone, subject, message, days, processed, note in APPEALS:
                db.session.add(Appeal(
                    name=name, email=email, phone=phone, subject=subject, message=message,
                    consent=True, created_at=datetime.now() - timedelta(days=days),
                    is_processed=processed, note=note,
                ))
            db.session.commit()

        print("База наполнена.")
        if os.environ.get("ADMIN_PASSWORD"):
            # Пароль в логи сборки не пишем
            print(f"Админка: /admin  — логин {ADMIN_LOGIN}, пароль из ADMIN_PASSWORD")
        else:
            print(f"Админка: /admin  — логин {ADMIN_LOGIN}, пароль {ADMIN_PASSWORD}")
