"""Автоинициализация базы на хостинге без SSH (CGI-развёртывание).

На виртуальном хостинге (Apache mod_cgi) нет SSH и нет возможности запустить
`python app.py seed` вручную. Поэтому при первом CGI-запросе, если в .env
задано AUTO_INIT_DB=1, приложение само:

  1. применяет миграции (схема базы),
  2. создаёт обязательную структуру: администратора, настройки, страницы,
     меню, площадки, жанры, фестивали — без демо-контента.

Демо-контент (концерты, новости, картинки) на хостинг не создаётся:
его заменяют настоящими через панель администратора.

Пароль администратора берётся из ADMIN_PASSWORD (см. .env.example).
Без него создаётся пароль по умолчанию — его нужно сменить в панели.

Функцию вызывает index.cgi на каждый запрос. Чтобы не гонять миграции
на каждый запрос, сначала быстрая проверка: если администратор уже есть,
база инициализирована и ничего не делаем.
"""
import os

from . import seed
from .models import User


def _auto_init_requested() -> bool:
    return os.environ.get("AUTO_INIT_DB", "").strip().lower() in ("1", "true", "yes", "on")


def auto_init_db(app) -> None:
    """Инициализирует базу при первом CGI-запросе, если AUTO_INIT_DB=1.

    Вызывается из index.cgi до обработки запроса. Ошибки не прерывают
    запрос: сайт должен работать, даже если инициализация не удалась
    (например, нет прав на запись) — об ошибках пишет в журнал.
    """
    if not _auto_init_requested():
        return
    try:
        # Быстрый путь: админ уже есть — база готова, миграции не гоняем.
        with app.app_context():
            try:
                if User.query.count() > 0:
                    return
            except Exception:
                pass  # таблиц ещё нет — инициализируем ниже
        # seed.run сам применяет миграции и создаёт структуру (без демо-контента).
        seed.run(app, structure_only=True)
    except Exception:
        app.logger.exception("AUTO_INIT_DB: не удалось инициализировать базу")
